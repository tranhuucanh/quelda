//! `manifest.json` and writing/checking the fixtures directory.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use serde_json::{Value, json};

use crate::fixtures::Fixture;
use crate::rules::{CATEGORIES, Preset, RULES, action, category_of, expected};

/// Manifest format version; bump on breaking changes.
pub const FORMAT: u32 = 1;

const README: &str = "# tests/fixtures (generated — do not edit)

Generated by `cargo run -p quelda-testkit --bin gen-fixtures`. Deterministic: rerunning
produces identical bytes. Not committed (ADR #12); regenerate after cloning.

All payloads are inert markers (`app.alert('quelda-test')`, PostScript `showpage`,
`quelda-test.txt`, `https://example.invalid/…`). No real exploit, shellcode or system command.

- `benign/`     clean files (some legitimately trip a warn-level rule; see manifest)
- `filetype/`   non-PDF files named .pdf (PostScript, EPS, SVG, MVG, MSL, HTML, ZIP…)
- `malformed/`  broken files and resource bombs (engine must not crash; bombs → ERROR)
- `rules/<RULE_ID>/bad/`   the rule must fire (plus evasion variants)
- `rules/<RULE_ID>/good/`  near-misses: the rule must not fire

`manifest.json` lists, per file, the rules that must fire (`fires`, `match`: exact or
at_least), whether the engine must stop with ERROR (`engine_error`: issue code prefix),
and the expected verdict per preset. It is the spec for rule and conformance tests.
";

fn fixture_json(f: &Fixture) -> Value {
    let mut expected_by_preset = serde_json::Map::new();
    for p in Preset::ALL {
        let e = expected(&f.fires, f.engine_error.is_some(), p);
        expected_by_preset.insert(
            p.key().to_string(),
            json!({ "status": e.status, "violations": e.violations, "warnings": e.warnings }),
        );
    }
    json!({
        "kind": f.kind.key(),
        "rule": f.rule,
        "variant": f.variant,
        "fires": f.fires,
        "match": if f.exact { "exact" } else { "at_least" },
        "engine_error": f.engine_error,
        "expected": expected_by_preset,
        "bytes": f.bytes.len(),
        "note": f.note,
    })
}

/// The manifest as pretty JSON (keys sorted, stable across runs).
pub fn manifest_json(fixtures: &[Fixture]) -> String {
    let rules: Vec<Value> = RULES
        .iter()
        .map(|r| {
            let presets: BTreeMap<&str, &str> = Preset::ALL.iter().map(|p| (p.key(), action(r.id, *p).key())).collect();
            json!({ "id": r.id, "category": category_of(r.id), "locked": r.locked, "presets": presets })
        })
        .collect();
    let categories: Vec<&str> = CATEGORIES.iter().map(|c| c.0).collect();
    let files: BTreeMap<&str, Value> = fixtures
        .iter()
        .map(|f| (f.path.as_str(), fixture_json(f)))
        .collect();
    let doc = json!({
        "format": FORMAT,
        "generator": format!("quelda-testkit {}", crate::version()),
        "categories": categories,
        "rules": rules,
        "files": files,
    });
    let mut s = serde_json::to_string_pretty(&doc).unwrap_or_default();
    s.push('\n');
    s
}

/// `<workspace>/tests/fixtures`.
pub fn default_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures")
}

/// The fixtures dir if it has been generated, else an error telling how to generate it.
pub fn require_dir(dir: &Path) -> Result<PathBuf, String> {
    if dir.join("manifest.json").is_file() {
        Ok(dir.to_path_buf())
    } else {
        Err(format!(
            "fixtures not found at {}: run `cargo run -p quelda-testkit --bin gen-fixtures` first",
            dir.display()
        ))
    }
}

/// Every file the generator owns, relative path → bytes.
pub fn expected_files(fixtures: &[Fixture]) -> BTreeMap<String, Vec<u8>> {
    let mut files: BTreeMap<String, Vec<u8>> = fixtures
        .iter()
        .map(|f| (f.path.clone(), f.bytes.clone()))
        .collect();
    files.insert("manifest.json".into(), manifest_json(fixtures).into_bytes());
    files.insert("README.md".into(), README.as_bytes().to_vec());
    files
}

fn walk(dir: &Path, root: &Path, out: &mut BTreeSet<String>) -> io::Result<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            walk(&path, root, out)?;
        } else if let Ok(rel) = path.strip_prefix(root) {
            out.insert(rel.to_string_lossy().replace('\\', "/"));
        }
    }
    Ok(())
}

/// Files under `dir` that the generator would write/remove/change. Empty = up to date.
pub fn diff_dir(dir: &Path, fixtures: &[Fixture]) -> io::Result<Vec<String>> {
    let want = expected_files(fixtures);
    let mut have = BTreeSet::new();
    if dir.is_dir() {
        walk(dir, dir, &mut have)?;
    }
    let mut diffs = Vec::new();
    for (path, bytes) in &want {
        match fs::read(dir.join(path)) {
            Ok(cur) if &cur == bytes => {}
            Ok(_) => diffs.push(format!("changed: {path}")),
            Err(_) => diffs.push(format!("missing: {path}")),
        }
    }
    for path in have {
        if !want.contains_key(&path) && is_generated(&path) {
            diffs.push(format!("stale: {path}"));
        }
    }
    Ok(diffs)
}

/// Only files the generator could have produced are ever removed.
fn is_generated(path: &str) -> bool {
    path.ends_with(".pdf") || path == "manifest.json" || path == "README.md"
}

/// Writes all fixtures to `dir` and removes stale generated files. Returns the file count.
pub fn write_dir(dir: &Path, fixtures: &[Fixture]) -> io::Result<usize> {
    let want = expected_files(fixtures);
    if dir.is_dir() {
        let mut have = BTreeSet::new();
        walk(dir, dir, &mut have)?;
        for path in have {
            if !want.contains_key(&path) && is_generated(&path) {
                fs::remove_file(dir.join(&path))?;
            }
        }
    }
    for (path, bytes) in &want {
        let target = dir.join(path);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)?;
        }
        if fs::read(&target).ok().as_deref() != Some(bytes.as_slice()) {
            fs::write(&target, bytes)?;
        }
    }
    Ok(want.len())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::fixtures::Kind;

    fn tiny() -> Vec<Fixture> {
        crate::fixtures::all()
            .into_iter()
            .filter(|f| f.kind == Kind::Benign)
            .take(2)
            .collect()
    }

    #[test]
    fn manifest_lists_files_rules_and_presets() {
        let fx = tiny();
        let m: Value = serde_json::from_str(&manifest_json(&fx)).unwrap();
        assert_eq!(m["format"], FORMAT);
        assert_eq!(m["rules"].as_array().unwrap().len(), RULES.len());
        let first = &m["files"][fx[0].path.as_str()];
        assert_eq!(first["expected"]["balanced"]["status"], "PASS");
        assert_eq!(first["match"], "exact");
    }

    #[test]
    fn require_dir_explains_how_to_generate() {
        let err = require_dir(Path::new("/nonexistent/quelda")).unwrap_err();
        assert!(err.contains("gen-fixtures"));
    }

    #[test]
    fn write_then_diff_is_clean_and_removes_stale() {
        let dir =
            std::env::temp_dir().join(format!("quelda-testkit-manifest-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        let fx = tiny();
        fs::create_dir_all(dir.join("benign")).unwrap();
        fs::write(dir.join("benign/stale.pdf"), b"old").unwrap();
        fs::write(dir.join("keep-me.txt"), b"not generated").unwrap();
        let n = write_dir(&dir, &fx).unwrap();
        assert_eq!(n, fx.len() + 2);
        assert!(diff_dir(&dir, &fx).unwrap().is_empty());
        assert!(!dir.join("benign/stale.pdf").exists());
        assert!(dir.join("keep-me.txt").exists());
        fs::write(dir.join(&fx[0].path), b"tampered").unwrap();
        assert_eq!(
            diff_dir(&dir, &fx).unwrap(),
            vec![format!("changed: {}", fx[0].path)]
        );
        fs::remove_dir_all(&dir).unwrap();
    }
}
